const SKIP_BUILD = process.argv.includes('--skip-build');
const LIGHT = process.argv.includes('--light');

function log(msg) {
  console.log(`\n▸ ${msg}`);
}

function run(cmd) {
  console.log(`$ ${cmd}`);
  execSync(cmd, { cwd: root, stdio: 'inherit' });
}

