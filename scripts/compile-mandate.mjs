/** Compile paired mandate artifacts using EVM instructions supported by Avalanche. */
import solc from 'solc';
import { readFile, writeFile } from 'node:fs/promises';
const source = await readFile('packages/contracts/src/BagMandate.sol', 'utf8');
const output = JSON.parse(solc.compile(JSON.stringify({ language: 'Solidity', sources: { 'BagMandate.sol': { content: source } },
  settings: { optimizer: { enabled: true, runs: 200 }, evmVersion: 'paris', outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object'] } } } })));
const errors = (output.errors ?? []).filter(error => error.severity === 'error');
if (errors.length) throw Error(errors.map(error => error.formattedMessage).join('\n'));
const artifact = output.contracts['BagMandate.sol'].BagMandate;
await writeFile('packages/onchain/src/abi.ts', `// Generated by scripts/compile-mandate.mjs.\nexport const BagMandateAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`);
await writeFile('packages/onchain/src/bytecode.ts', `// Generated by scripts/compile-mandate.mjs.\nexport const BagMandateBytecode = '0x${artifact.evm.bytecode.object}' as const;\n`);
