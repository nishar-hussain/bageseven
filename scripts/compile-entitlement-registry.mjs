/** Rebuild the BagEntitlementRegistry ABI and bytecode used by Avalanche deployments. */
import solc from 'solc';
import { readFile, writeFile } from 'node:fs/promises';

const source = await readFile('packages/contracts/src/BagEntitlementRegistry.sol', 'utf8');
const output = JSON.parse(solc.compile(JSON.stringify({
  language: 'Solidity',
  sources: { 'BagEntitlementRegistry.sol': { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    // Fuji currently requires Paris-compatible creation bytecode.
    evmVersion: 'paris',
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode', 'evm.deployedBytecode'] } },
  },
})));
const errors = (output.errors ?? []).filter((error) => error.severity === 'error');
if (errors.length) throw Error(errors.map((error) => error.formattedMessage).join('\n'));
const artifact = output.contracts['BagEntitlementRegistry.sol'].BagEntitlementRegistry;
await writeFile(
  'packages/onchain/src/entitlement-registry-artifact.ts',
  `// Generated by scripts/compile-entitlement-registry.mjs.\nexport const EntitlementRegistryAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\nexport const EntitlementRegistryBytecode = '0x${artifact.evm.bytecode.object}' as const;\nexport const EntitlementRegistryRuntime = '0x${artifact.evm.deployedBytecode.object}' as const;\n`,
);
